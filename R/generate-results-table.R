#' Generate Results Table
#'
#' This function parses through the data/scores folders and generates
#' the results table for grading accuracy comparison.
#'
#' @param dir optionally, specify directory
#'
#' @returns a dataframe
#'
#' @export
generate_results_table <- function(dir = "."){
  dir = paste0(dir , "/data/scores/")
  courses <- list.dirs(path = dir,
                       full.names = F, recursive = FALSE)
  results_table <- data.frame()
  for (course in courses){
    row <- generate_results_row(dir = paste0(dir, course,"/"))
    results_table <- rbind(results_table, row)
  }

  return (results_table)
}

#' Generate Results Table in GT Format
#'
#' This function displays a results table in GT format.
#'
#' @param results_table results_table as generated by `generate_results_table`
#'
#' @returns a gt object
#' @importFrom gt gt tab_spanner cols_label_with
#' @importFrom tidyr starts_with
#'
#' @export
generate_gt_results_table <- function(results_table){
  gt::gt(results_table) |>
    gt::tab_spanner(
      label = "MAE",
      columns = starts_with("MAE_")
    ) |>
    gt::tab_spanner(
      label = "ISP",
      columns = starts_with("ISP_")
    ) |>
    gt::cols_label_with(
      tidyr::starts_with("MAE_"),
      ~ sub("^MAE_", "", .x)
    ) |>
    gt::cols_label_with(
      tidyr::starts_with("ISP_"),
      ~ sub("^ISP_", "", .x)
    )
}

#' @importFrom tibble tibble
#' @importFrom utils combn
#' @importFrom jsonlite fromJSON
generate_results_row <- function(dir) {

  files <- list.files(dir, pattern = "\\calibrated.csv$")
  metadata <- fromJSON(paste0(dir, "/metadata.json"))
  course_info <- metadata$course_info

  df <- data.frame(
    file = files,
    status = ifelse(
      grepl("-calibrated", files),
      "calibrated",
      "uncalibrated"
    ),
    name = sub("-.*$", "", files)
  )

  mae_vals <- list()
  isp_vals <- list()

  for (status in unique(df$status)) {
    group <- df[df$status == status, ]

    if (nrow(group) < 2) next

    pairs <- combn(seq_len(nrow(group)), 2)

    for (i in seq_len(ncol(pairs))) {
      f1 <- group$file[pairs[1, i]]
      f2 <- group$file[pairs[2, i]]

      n1 <- group$name[pairs[1, i]]
      n2 <- group$name[pairs[2, i]]

      pair_name <- paste0(n1, ".v.", n2)

      metrics <- compute_mae_and_isp(paste0(dir, f1), paste0(dir, f2))

      mae_vals[[pair_name]] <- metrics$MAE
      isp_vals[[pair_name]] <- metrics$ISP
    }
  }

  # Build single-row dataframe
  results_row <- tibble::tibble(
    `Question Name` = basename(dir),
    `Subject` = course_info$department,
    #`Course` = paste(course_info$department, course_info$course_number),
    #`Course Name` = course_info$course_name,
    `Course Level` = ifelse(course_info$upper_div,
                            "Upper Division", "Lower Division")
    #`Year` = paste(course_info$semester, course_info$year),
    #`Mode of Question` = course_info$mode_of_question,
    #`Medium of Answer` = course_info$medium_of_answer,
    #`Content of Answer` = course_info$content_of_answer,
  )

  for (nm in names(mae_vals)) {
    results_row[[paste0("MAE_", nm)]] <- mae_vals[[nm]]
  }

  for (nm in names(isp_vals)) {
    results_row[[paste0("ISP_", nm)]] <- isp_vals[[nm]]
  }

  return (results_row)
}
